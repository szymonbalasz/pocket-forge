// Collates results/raw/*.json into results/summary.md (committed; small).
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const raw = join(root, 'results', 'raw');
const all = readdirSync(raw).filter(f => f.endsWith('.json')).map(f => ({ f, d: JSON.parse(readFileSync(join(raw, f), 'utf8')) }));
const by = p => all.filter(x => x.f.startsWith(p)).map(x => x.d);
const out = ['# Canvas spike results', '', 'Generated by `node scripts/summarize.mjs` from `results/raw/` (not committed). Windows 11 laptop (Intel UHD iGPU = default, RTX 4080 Laptop dGPU via --force_high_performance_gpu), on AC power. Edge 157 (same Chromium as WebView2 157), viewport 1600×900, DPR 1, **vsync on, 240 Hz panel** (frames are vblank-quantised: 4.2 / 8.3 / 12.5 ms). Uncapped runs (vsync off) are kept out of this table: they showed WebGL back-pressure stalls that do not occur with vsync.', ''];

const perf = by('perf-');
if (perf.length) {
  out.push('## Large image display (9 s scripted pan/zoom)', '');
  out.push('| GPU | lib | mode | size | first view ms | decode ms | fps | frame p50 / p95 / p99 / max ms | frames > 33 ms | render CPU p95 ms | tile loads | GPU dedicated / shared MB | browser private MB | JS heap MB |');
  out.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
  for (const r of perf.sort((a, b) => (a.gpu + a.mode + a.size + a.lib).localeCompare(b.gpu + b.mode + b.size + b.lib))) {
    const p = r.panZoom, m = r.memAfter ?? {};
    out.push(`| ${r.gpu} | ${r.lib} | ${r.mode} | ${r.size} | ${r.load.ok === false ? `**fail (${r.load.stage}): ${r.load.error}**` : r.load.ttfvMs} | ${r.load.decodeMs ?? '–'} | ${p?.fps ?? '–'} | ${p ? `${p.frameP50} / ${p.frameP95} / ${p.frameP99} / ${p.frameMax}` : '–'} | ${p?.over33ms ?? '–'} | ${p?.cpuP95 ?? '–'} | ${p?.tileLoads ?? '–'} | ${m.gpuDedicatedMB ?? '?'} / ${m.gpuSharedMB ?? '?'} | ${m.privateMB ?? '?'} | ${m.jsHeapUsedMB ?? '?'} |`);
  }
  out.push('');
}

const mask = by('mask-');
if (mask.length) {
  out.push('## Mask painting (300 frames, r = 60 px, 50 % feather, every 3rd stroke erases, 16k tiles underneath)', '');
  out.push('| GPU | lib | region | storage | fps | frame p50 / p95 / max ms | CPU per frame p50 / p95 ms | dab CPU p95 ms | export (8-bit mask) ms |');
  out.push('|---|---|---|---|---|---|---|---|---|');
  for (const r of mask.sort((a, b) => (a.gpu + a.side + a.storage + a.lib).localeCompare(b.gpu + b.side + b.storage + b.lib)))
    out.push(`| ${r.gpu} | ${r.lib} | ${r.side}² | ${r.storage} | ${r.fps} | ${r.frameP50} / ${r.frameP95} / ${r.frameMax} | ${r.cpuP50} / ${r.cpuP95} | ${r.dabP95} | ${r.exportMs} |`);
  out.push('');
}

const coords = by('coords-');
if (coords.length) {
  out.push('## Coordinates (library-native transforms)', '');
  out.push('| lib | max round-trip error (image px) | max diff vs shared math (screen px) | pixel-identity mismatches | anchored-zoom drift, 2000 steps (image px) | rendered probe at (16000,16000), zoom 8 / 32: mismatches |');
  out.push('|---|---|---|---|---|---|');
  for (const x of all.filter(x => x.f.startsWith('coords-'))) {
    const d = x.d, lib = x.f.slice(7, -5);
    out.push(`| ${lib} | ${Math.max(...d.rows.map(r => r.roundTripMaxPx)).toExponential(1)} | ${Math.max(...d.rows.map(r => r.vsCoreMaxScreenPx))} | ${d.rows.reduce((a, r) => a + r.pixelMismatch, 0)} | ${d.anchorDriftMaxImagePx.toExponential(1)} | ${d.rendered.zoom8.mismatched}/${d.rendered.zoom8.samples} / ${d.rendered.zoom32.mismatched}/${d.rendered.zoom32.samples} |`);
  }
  out.push('');
}

const layers = all.filter(x => x.f.startsWith('layers-'));
if (layers.length) {
  out.push('## Patch layer', '', '| lib | corner error vs affine (image px) | move | scale handles | rotate handle | built in |', '|---|---|---|---|---|---|');
  for (const x of layers) out.push(`| ${x.f.slice(7, -5)} | ${x.d.cornerErrPx.toExponential(1)} | ${x.d.handles.move} | ${x.d.handles.scale} | ${x.d.handles.rotate} | ${x.d.handles.builtIn} |`);
  out.push('');
}

if (existsSync(join(raw, 'limits.json'))) {
  const l = JSON.parse(readFileSync(join(raw, 'limits.json'), 'utf8'));
  out.push('## Engine limits (measured)', '', '```json', JSON.stringify({ ...l.limits, webgpu: l.webgpu }, null, 1), '```', '');
}

for (const x of all.filter(x => x.f.startsWith('tauri-'))) {
  const slim = JSON.parse(JSON.stringify(x.d, (k, v) => (['long', 'info', 'limits'].includes(k) ? undefined : v)));
  out.push(`## Tauri smoke (${x.f.slice(6, -5)}, WebView2, iGPU, vsync on, debug build)`, '', '```json', JSON.stringify(slim, null, 1), '```', '');
}

writeFileSync(join(root, 'results', 'summary.md'), out.join('\n'));
console.log('wrote results/summary.md');
